import { describe, expect, it } from 'vitest';
import sharp from 'sharp';
import {
  applyRefineResults,
  parseRefineReply,
  planRefineCrops,
  type RefineCropSpec,
} from '../electron/llm/zoom-refine';
import {
  isOutOfImageBounds,
  isPhysicalSpaceEvidence,
  mapBoxToScreen,
  mapPointToScreen,
  parseAnnotations,
  physicalSpaceConsensus,
  rescalePhysicalTagToImage,
  type PointGeo,
} from '../electron/llm/point';

// End-to-end annotation pipeline over REAL pixels (sharp, no Electron):
//
// The failing session's geometry — img 1456x819 @ (0,0) of a 1536x864 DIP
// window at 1.25x display scaling, i.e. a 1920x1080 PHYSICAL grid. A model
// that writes native pixels emits tags like `y=886` that exceed BOTH the image
// (819) and the DIP window (864) but sit perfectly inside the physical grid.
//
// The chain under test mirrors handlers.ts finalize + correctAnnotGroup's
// zoom-refine (pass 2), but every pixel is REAL: a JPEG is rendered, the crop
// is extracted and upscaled with sharp, and the "vision" reply is generated by
// MEASURING the target's bounding box in the actual upscaled pixels — exactly
// what the refine model is asked to do. No mock geometry, no faked crops.

const GEO: PointGeo = {
  imgW: 1456,
  imgH: 819,
  absLeft: 0,
  absTop: 0,
  winW: 1536,
  winH: 864,
  agentUnitsPerDip: 1.25,
};

// A rendered "diagram": white canvas with a red-filled element. The element's
// TRUE image-space bounds are (30,362,607,152). Written by the provider in
// PHYSICAL pixels those become (40,477,801,200) — 1.3187x too big, exactly the
// observed session (boxes "wrong size at the wrong place", points dropped).
async function renderDiagram(): Promise<Buffer> {
  const w = GEO.imgW;
  const h = GEO.imgH;
  const px = new Uint8Array(w * h * 3).fill(255);
  const rect = { x: 30, y: 362, w: 607, h: 152 };
  for (let yy = rect.y; yy < rect.y + rect.h; yy += 1) {
    for (let xx = rect.x; xx < rect.x + rect.w; xx += 1) {
      const i = (yy * w + xx) * 3;
      px[i] = 205;
      px[i + 1] = 40;
      px[i + 2] = 40;
    }
  }
  return sharp(Buffer.from(px.buffer), { raw: { width: w, height: h, channels: 3 } })
    .jpeg({ quality: 96 })
    .toBuffer();
}

// The "vision" step: extract the crop from the real JPEG, upscale like the
// refine call does, and MEASURE the red element's bounds in payload pixels —
// the model's `x,y,w,h` box reply.
async function measureBoxInCrop(
  jpeg: Buffer,
  spec: RefineCropSpec,
): Promise<{ x: number; y: number; w: number; h: number }> {
  const outW = spec.crop.w * spec.scale;
  const outH = spec.crop.h * spec.scale;
  const buf = await sharp(jpeg)
    .extract({ left: spec.crop.x, top: spec.crop.y, width: spec.crop.w, height: spec.crop.h })
    .resize(outW, outH, { kernel: 'nearest' })
    .raw()
    .toBuffer();
  let minX = Infinity;
  let minY = Infinity;
  let maxX = -1;
  let maxY = -1;
  for (let y = 0; y < outH; y += 1) {
    for (let x = 0; x < outW; x += 1) {
      const i = (y * outW + x) * 3;
      const r = buf[i];
      const g = buf[i + 1];
      const b = buf[i + 2];
      if (r > 180 && g < 120 && b < 120) {
        if (x < minX) minX = x;
        if (x > maxX) maxX = x;
        if (y < minY) minY = y;
        if (y > maxY) maxY = y;
      }
    }
  }
  if (maxX < 0) throw new Error('shot: target not found in refined crop');
  return { x: minX, y: minY, w: maxX - minX + 1, h: maxY - minY + 1 };
}

describe('annotation pipeline end-to-end (physical-px rescue → zoom-refine → DIP)', () => {
  it('flips a whole physical-px run, measures the box in real pixels, and lands exact DIP', async () => {
    const jpeg = await renderDiagram();

    // 1. The model's raw tags — physical-px (the two points are "past the
    //    window but on the screen", the box is 1.3187x too big in-place).
    const raw = parseAnnotations(
      '[BOX:40,477,801,200:cyclododecatriene:screen0] ' +
        '[POINT:554,886:Intermediate:screen0] [POINT:841,886:Product:screen0]',
    );
    expect(raw.map((t) => t.kind)).toEqual(['box', 'point', 'point']);

    // 2. handlers.ts finalize normalize: physical evidence = the two OOB
    //    points => 2/3 consensus => whole run rescaled from physical px.
    const physEvidence = raw.filter((tag) => isPhysicalSpaceEvidence(tag, GEO));
    expect(physEvidence).toHaveLength(2);
    expect(physicalSpaceConsensus(physEvidence.length, raw.length)).toBe(true);

    const normalized = raw.map((tag) => rescalePhysicalTagToImage(tag, GEO));
    const box = normalized[0];
    const [p1, p2] = [normalized[1], normalized[2]];
    if (box.kind !== 'box') throw new Error('shot: box');
    if (p1.kind !== 'point' || p2.kind !== 'point') throw new Error('shot: point');
    // Phys px 1.3187 → image px: box now the TRUE size, points now in-bounds.
    expect(box).toMatchObject({ kind: 'box', x: 30, y: 362, w: 607, h: 152 });
    expect(p1).toMatchObject({ x: 420, y: 672 });
    expect(p2).toMatchObject({ x: 638, y: 672 });
    expect(isOutOfImageBounds({ x: p1.x, y: p1.y }, GEO)).toBe(false);

    // 3. zoom-refine: plan a crop that CONTAINS the whole box, extract + upsample
    //    the REAL pixels, and let the "model" measure the bounds. (The two
    //    points get their own refine crops — only the BOX is measured here.)
    const specs = planRefineCrops(normalized, GEO.imgW, GEO.imgH, null);
    const spec = specs.find((s) => s.model === 'box');
    expect(spec).toBeDefined();
    expect(spec!.crop.x).toBeLessThanOrEqual(30);
    expect(spec!.crop.y).toBeLessThanOrEqual(362);
    expect(spec!.crop.x + spec!.crop.w).toBeGreaterThanOrEqual(30 + 607);
    expect(spec!.crop.y + spec!.crop.h).toBeGreaterThanOrEqual(362 + 152);

    const measured = await measureBoxInCrop(jpeg, spec!);
    // The "vision" reply lies within ~1-2px of the element's true bounds
    // (real JPEG edge ringing) — the model's box measurement precision.
    expect(measured.x).toBeGreaterThanOrEqual(30 - 2);
    expect(measured.x).toBeLessThanOrEqual(30 + 2);
    expect(measured.y).toBeGreaterThanOrEqual(362 - 2);
    expect(measured.y).toBeLessThanOrEqual(362 + 2);
    expect(measured.w).toBeGreaterThanOrEqual(607 - 3);
    expect(measured.h).toBeGreaterThanOrEqual(152 - 3);
    const reply = parseRefineReply(`${measured.x},${measured.y},${measured.w},${measured.h}`);
    expect(reply).not.toBeNull();

    const refined = applyRefineResults(normalized, [{ spec: spec!, result: reply }], GEO.imgW, GEO.imgH);
    if (refined[0].kind !== 'box') throw new Error('shot: refined box');
    // The measured bounds REPLACE the tag's (wrong-scaled) w/h — lands just
    // under the true 607x152 (JPEG edge), never the 801x200 wrong-space size.
    expect(refined[0].w).toBeGreaterThanOrEqual(604);
    expect(refined[0].w).toBeLessThanOrEqual(610);
    expect(refined[0].h).toBeGreaterThanOrEqual(149);
    expect(refined[0].h).toBeLessThanOrEqual(155);

    // 4. Map to screen DIP (win/img per axis) — the numbers the overlay draws.
    //    The box lands within ~2 DIP of the exact spot (32,382,640,160).
    const dipBox = mapBoxToScreen(refined[0], GEO)!;
    expect(Math.abs(dipBox.x - 32)).toBeLessThanOrEqual(2);
    expect(Math.abs(dipBox.y - 382)).toBeLessThanOrEqual(2);
    expect(Math.abs(dipBox.w - 640)).toBeLessThanOrEqual(2);
    expect(Math.abs(dipBox.h - 160)).toBeLessThanOrEqual(2);
    expect(
      mapPointToScreen({ x: p1.x, y: p1.y, label: p1.label, screen: p1.screen }, GEO),
    ).toEqual({ x: 443, y: 709 });
    expect(
      mapPointToScreen({ x: p2.x, y: p2.y, label: p2.label, screen: p2.screen }, GEO),
    ).toEqual({ x: 673, y: 709 });
  });

  it('rescues OOB physical-px points per-tag even when the run has no consensus', async () => {
    // The observed 2/5 run: three in-image tags (could be either space) and two
    // OOB physical-px points. No whole-run flip — but the unambiguous points are
    // still rescued individually instead of dropped.
    const raw = parseAnnotations(
      '[BOX:40,477,801,200:cyclododecatriene:screen0] ' +
        '[BOX:40,634,801,200:benzene ring:screen0] [POINT:911,678:arrow label:screen0] ' +
        '[POINT:554,886:Intermediate:screen0] [POINT:841,886:Product:screen0]',
    );
    expect(raw).toHaveLength(5);
    const physEvidence = raw.filter((tag) => isPhysicalSpaceEvidence(tag, GEO));
    expect(physEvidence).toHaveLength(2);
    expect(physicalSpaceConsensus(physEvidence.length, raw.length)).toBe(false);

    const normalized = raw.map((tag) =>
      physicalSpaceConsensus(physEvidence.length, raw.length) || isPhysicalSpaceEvidence(tag, GEO)
        ? rescalePhysicalTagToImage(tag, GEO)
        : tag,
    );
    // In-image tags untouched (no consensus), the two OOB points recovered.
    expect(normalized[0]).toEqual(raw[0]);
    expect(normalized[3]).toMatchObject({ kind: 'point', x: 420, y: 672 });
    expect(normalized[4]).toMatchObject({ kind: 'point', x: 638, y: 672 });
    for (const t of normalized) {
      if (t.kind === 'point') {
        expect(isOutOfImageBounds({ x: t.x, y: t.y }, GEO)).toBe(false);
        expect(mapPointToScreen({ x: t.x, y: t.y, label: t.label, screen: t.screen }, GEO)).not.toBeNull();
      }
    }
  });

  it('never fires a physical-px flip when there is no scale factor (1:1 DIP)', async () => {
    const raw = parseAnnotations('[POINT:554,886:x:screen0]');
    const flat: PointGeo = { ...GEO, agentUnitsPerDip: 1 };
    // y=886 exceeds both the image and the (1:1) window — unrescuable garbage.
    expect(rescalePhysicalTagToImage(raw[0], flat)).toEqual(raw[0]);
    expect(isPhysicalSpaceEvidence(raw[0], flat)).toBe(false);
    expect(isOutOfImageBounds({ x: raw[0].x, y: raw[0].y }, flat)).toBe(true);
  });
});