// Generates electron/llm/openui-prompt.generated.ts from the REAL OpenUI
// component library (@openuidev/react-ui). The signatures are never hand-
// written here — they are read from the library's own prompt spec, so the model
// is always taught exactly what the renderer can draw.
import { writeFileSync } from 'node:fs';
import { openuiChatLibrary, openuiChatPromptOptions } from '@openuidev/react-ui/genui-lib';

const KEEP = [
  'Card', 'CardHeader', 'TextContent', 'MarkDownRenderer',
  'Callout', 'TextCallout', 'InlineHeader',
  'CodeBlock', 'Separator', 'Table', 'Col',
  'BarChart', 'LineChart', 'AreaChart', 'PieChart', 'Series',
  'Form', 'FormControl', 'Label', 'Input', 'TextArea', 'Select', 'SelectItem',
  'DatePicker', 'Slider', 'CheckBoxGroup', 'CheckBoxItem',
  'RadioGroup', 'RadioItem', 'SwitchGroup', 'SwitchItem',
  'Button', 'Buttons', 'ListBlock', 'ListItem',
  'FollowUpBlock', 'FollowUpItem', 'Steps', 'StepsItem',
  'TagBlock', 'Tag', 'MetricIndicatorInline', 'OptionCards', 'OptionCard',
  'Image', 'ImageBlock', 'Chips', 'ChipItem',
];

const spec = openuiChatLibrary.toSpec();
const lines = [];
for (const name of KEEP) {
  const c = spec.components[name];
  if (!c) throw new Error(`[gen-openui-prompt] library no longer exports component: ${name}`);
  lines.push(`- ${c.signature}`);
}

const rules = [
  '## Structured answers use OpenUI Lang',
  'When the answer carries structure (metrics, comparisons, tables, dashboards, forms, steps, choices, actions) put it in ONE [OPENUI] block instead of prose bullets.',
  'Syntax: one statement per line, `name = Component(arg1, arg2, ...)`; arguments are POSITIONAL; `root = Card(...)` is the entry point; every named statement must be referenced by a parent array.',
  'Wrap the whole program between [OPENUI] and [/OPENUI] on their own lines. Emit at most one [OPENUI] block per answer, before the short prose summary.',
  'Buttons run real actions: `Button("Ask more", Action([@ToAssistant("follow-up prompt")]))` sends a new prompt; `@OpenUrl("https://…")` opens a link; `@Copy("text")` copies text to the clipboard. Pick the action the user would want next — never a dead-end button.',
  'Forms collect values into `$field` bindings; give the Form a name and a Buttons child whose Button runs `@ToAssistant("…")` so submitting sends the answers. Only ask 1-3 fields, with sensible placeholder or default values.',
  'Keep it compact and readable: 3-8 statements, meaningful titles, no raw JSON, no markdown fences inside the block. Put the [OPENUI] block FIRST, then at most 2-3 sentences of prose that add what the UI cannot show.',
];

const text = [
  ...rules,
  '',
  '### Component signatures (OpenUI Lang 1.0)',
  ...lines,
  '',
  'Example:',
  '[OPENUI]',
  'root = Card([hdr, ttl, tbl, act])',
  'hdr = CardHeader("Q3 revenue")',
  'ttl = TextContent("Revenue grew 18% quarter over quarter.", "small")',
  'tbl = Table([Col("Region", ["EMEA", "APAC"]), Col("Revenue", ["$4.2M", "$2.8M"])])',
  'act = Buttons([Button("Break this down by month", Action([@ToAssistant("Break the Q3 revenue table down by month")])), Button("Copy table", Action([@Copy("Q3 revenue: EMEA $4.2M, APAC $2.8M")]))])',
  '[/OPENUI]',
  '',
  'Example with a form:',
  '[OPENUI]',
  'root = Card([hdr, f])',
  'hdr = CardHeader("Refactor plan")',
  'f = Form("refactor", btn, [inp, sel])',
  'inp = Input("scope", "src/llm/*.ts")',
  'sel = Select("strategy", [SelectItem("safe", "Safe, small steps"), SelectItem("fast", "Fast rewrite")])',
  'btn = Buttons([Button("Generate steps", Action([@ToAssistant("Generate the refactor steps")]))])',
  '[/OPENUI]',
].join('\n');

const out = `// GENERATED by scripts/gen-openui-prompt.mjs — do not edit by hand.
// Signatures come from the real @openuidev/react-ui chat library, so the model
// is taught exactly the components the OpenUI renderer can draw.
export const OPENUI_PROMPT = ${JSON.stringify(text)};
`;

writeFileSync(new URL('../electron/llm/openui-prompt.generated.ts', import.meta.url), out, 'utf8');
console.log(`wrote openui-prompt.generated.ts — ${KEEP.length} components, ${text.length} chars`);
